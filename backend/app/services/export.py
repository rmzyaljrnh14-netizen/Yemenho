"""Excel and PDF export for national reports (v0.5).

Both formats are built in memory and returned as bytes. Arabic text is shaped
and bidi-reordered for the PDF because reportlab does not do that itself.

Font handling: we look for a Noto Arabic TTF in a list of well-known locations
(bundled assets first, then common system paths). If none is found we still
produce a PDF, but Arabic glyphs fall back to the built-in font, so the caller
should ship the font. The exported file always says it is generated by the
system and, when applicable, that it is demo data.
"""
from __future__ import annotations

import io
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet

FONT_CANDIDATES = [
    Path(__file__).resolve().parents[1] / "assets" / "fonts" / "NotoSansArabic-Regular.ttf",
    Path("/usr/share/fonts/truetype/noto/NotoSansArabic-Regular.ttf"),
    Path("C:/Windows/Fonts/segoeui.ttf"),
    Path("/Library/Fonts/Arial Unicode.ttf"),
]
FONT_BOLD_CANDIDATES = [
    Path(__file__).resolve().parents[1] / "assets" / "fonts" / "NotoSansArabic-Bold.ttf",
    Path("/usr/share/fonts/truetype/noto/NotoSansArabic-Bold.ttf"),
    Path("C:/Windows/Fonts/segoeuib.ttf"),
    Path("/Library/Fonts/Arial Unicode.ttf"),
]

_AR_FONT = "NotoArabic"
_AR_FONT_BOLD = "NotoArabic-Bold"


def _find(candidates: list[Path]) -> Path | None:
    for c in candidates:
        if c.exists():
            return c
    return None


def _register_fonts() -> tuple[str, str]:
    """Register an Arabic-capable font; fall back to Helvetica."""
    regular = _find(FONT_CANDIDATES)
    bold = _find(FONT_BOLD_CANDIDATES) or regular
    if regular is None:
        return "Helvetica", "Helvetica-Bold"
    try:
        pdfmetrics.registerFont(TTFont(_AR_FONT, str(regular)))
        pdfmetrics.registerFont(TTFont(_AR_FONT_BOLD, str(bold)))
        return _AR_FONT, _AR_FONT_BOLD
    except Exception:
        return "Helvetica", "Helvetica-Bold"


def _shape_ar(text: object) -> str:
    """Shape and reorder Arabic text for correct RTL rendering."""
    s = "" if text is None else str(text)
    if not s:
        return s
    try:
        import arabic_reshaper
        from bidi.algorithm import get_display

        return get_display(arabic_reshaper.reshape(s))
    except Exception:
        return s


def _fmt(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.2f}".rstrip("0").rstrip(".")
    return str(value)


def build_excel(
    *,
    title: str,
    subtitle: str,
    columns: list[str],
    rows: list[list[object]],
    sheet_name: str = "التقرير",
) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_name[:31] or "التقرير"
    ws.sheet_view.rightToLeft = True

    ws.append([title])
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=max(len(columns), 1))
    ws.cell(row=1, column=1).font = Font(bold=True, size=14)
    ws.cell(row=1, column=1).alignment = Alignment(horizontal="center", vertical="center")
    ws.append([subtitle])
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=max(len(columns), 1))
    ws.cell(row=2, column=1).font = Font(size=10, color="666666")
    ws.cell(row=2, column=1).alignment = Alignment(horizontal="center", vertical="center")
    ws.append([])

    header_row = ws.max_row + 1
    ws.append(columns)
    fill = PatternFill("solid", fgColor="1F5C4D")
    for col in range(1, len(columns) + 1):
        cell = ws.cell(row=header_row, column=col)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = fill
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    for r in rows:
        ws.append(r)

    for col in range(1, len(columns) + 1):
        letter = get_column_letter(col)
        width = max(
            [len(str(columns[col - 1]))]
            + [len(str(r[col - 1])) if col - 1 < len(r) else 0 for r in rows]
            + [10]
        )
        ws.column_dimensions[letter].width = min(max(width + 2, 12), 45)

    for row in ws.iter_rows(min_row=header_row + 1):
        for cell in row:
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=False)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def build_pdf(
    *,
    title: str,
    subtitle: str,
    columns: list[str],
    rows: list[list[object]],
    note: str | None = None,
    footer: str | None = None,
) -> bytes:
    regular, bold = _register_fonts()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=landscape(A4),
        rightMargin=12 * mm,
        leftMargin=12 * mm,
        topMargin=12 * mm,
        bottomMargin=12 * mm,
        title=title,
    )

    styles = getSampleStyleSheet()
    h_style = ParagraphStyle(
        "ArTitle", parent=styles["Title"], fontName=bold, fontSize=16, alignment=1, spaceAfter=4
    )
    sub_style = ParagraphStyle(
        "ArSub", parent=styles["Normal"], fontName=regular, fontSize=10, alignment=1,
        textColor=colors.HexColor("#555555"),
    )
    cell_style = ParagraphStyle("ArCell", parent=styles["Normal"], fontName=regular, fontSize=8, alignment=1)
    head_style = ParagraphStyle(
        "ArHead", parent=styles["Normal"], fontName=bold, fontSize=8, alignment=1,
        textColor=colors.white,
    )

    story = [Paragraph(_shape_ar(title), h_style), Paragraph(_shape_ar(subtitle), sub_style), Spacer(1, 6)]
    if note:
        story.append(Paragraph(_shape_ar(note), sub_style))
        story.append(Spacer(1, 6))

    data = [[Paragraph(_shape_ar(c), head_style) for c in columns]]
    for r in rows:
        data.append([Paragraph(_shape_ar(_fmt(v)), cell_style) for v in r])

    table = Table(data, repeatRows=1, hAlign="CENTER")
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F5C4D")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CCCCCC")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F2F6F4")]),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]
        )
    )
    story.append(table)
    if footer:
        story.append(Spacer(1, 8))
        story.append(Paragraph(_shape_ar(footer), sub_style))

    doc.build(story)
    return buf.getvalue()
